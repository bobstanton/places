import esbuild from "esbuild";
import process from "process";
import { renameBundledCssPlugin } from "./esbuild.shared.mjs";
import { builtinModules } from "node:module";
import inlineWorkerPlugin from "esbuild-plugin-inline-worker";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const watchMode = (process.argv[2] === "watch");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [
		renameBundledCssPlugin,
		inlineWorkerPlugin({
			// Worker-specific build options
			target: "es2022",
			format: "iife",
			minify: prod,
			// Do not externalize Obsidian here. A worker cannot load it, so any
			// accidental dependency must fail the build instead of failing at runtime.
		}),
	],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	minify: prod,
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
});

if (watchMode) {
	await context.watch();
} else {
	await context.rebuild();
	process.exit(0);
}
